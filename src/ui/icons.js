export const iconCache = new Map();
export function icon(name, x, y, scale, tint){
  const key = name+'|'+(scale||1)+'|'+(tint||'');
  let c = iconCache.get(key);
  if (!c){
    const sp = ICONS[name]; if (!sp) return;
    const w = sp[0].length, h = sp.length, s = scale||1;
    c = document.createElement('canvas'); c.width = w*s; c.height = h*s;
    const g = c.getContext('2d');
    for (let r=0;r<h;r++) for (let col=0;col<w;col++){
      const ch = sp[r][col];
      if (ch === '.' || !ICON_PAL[ch]) continue;
      g.fillStyle = tint || ICON_PAL[ch];
      g.fillRect(col*s, r*s, s, s);
    }
    iconCache.set(key, c);
  }
  P.drawImage(c, Math.round(x), Math.round(y));
  return c;
}
